#!/usr/bin/env python3
"""
32_assay_designs_doc.py -- generate docs/ASSAY_DESIGNS.md, the per-candidate bench plan.

Everything in the document is read from the tables; nothing is typed by hand. Each
candidate gets: what structurally changed, whether short-read Illumina could have found
it, which assay can resolve it and why, the actual oligos with their measured off-target
counts, the expected readout in BOTH isoforms, what result would support the switch, and
what result would falsify it.
"""
import csv, os
from collections import defaultdict, Counter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)

rd = lambda p: list(csv.DictReader(open(p)))
assign = rd("results/tables/assay_assignment.csv")
order = rd("results/tables/assay_order_sheet.csv")
regions = {r["isoform_id"]: r for r in rd("results/tables/discriminating_regions.csv")}
seqver = {r["isoform_id"]: r for r in rd("results/tables/sequence_verification.csv")}
prep = defaultdict(list)
for r in rd("results/tables/pair_selection_report.csv"):
    prep[r["isoform_id"]].append(r)

# NOT candidate_detectability_by_switch.csv -- that table was built on the earlier 63-gene
# list, also has 44 rows by coincidence, and shares no isoform_id with this shortlist, so
# joining on it silently yields empty platform columns. 33 recomputes it for these 44.
detect = {}
for r in rd("results/tables/shortlist_platform.csv"):
    detect[r["isoform_id"]] = r
assert detect, "shortlist_platform.csv is empty"
_miss = [a["gene_name"] for a in assign if a["isoform_id"] not in detect]
assert not _miss, f"no platform record for: {_miss[:5]}"

oligos = defaultdict(list)
for o in order:
    oligos[o["isoform_id"]].append(o)

B = lambda v: str(v).strip().lower() == "true"
F = lambda v: float(v) if v not in ("", None) else 0.0

# power floor from the donor-variance diagnostic (23): minimum detectable |dIF| at
# n=3, 80% power -- 0.172 in primary MDM, 0.156 in THP-1
POWER = {"primary MDM (H)": 0.172, "THP-1 (T)": 0.156}

CONTROLS = {
    "5' RACE": [
        "No-RT control on the same RNA: a band in the minus-RT lane means genomic DNA, and every TSS call from that sample is void.",
        "No-template control in both the first and the nested PCR.",
        "A positive-control GSP against a gene with a single annotated TSS, run in the same reaction batch, to show the RACE adapter ligation worked.",
        "Both the -LPS and +LPS samples must be processed in the same batch; a TSS ratio compared across batches is not interpretable.",
        "Sequence the products. A size shift on a gel is suggestive; only the sequence establishes which TSS was used.",
    ],
    "qPCR": [
        "Standard curve across at least 5 logs for each primer pair, with efficiency 90-110%; an isoform-fraction comparison between two pairs of differing efficiency is not valid.",
        "Melt curve on every reaction: a single peak. These primers were selected against the transcriptome, but a second peak means a second product regardless.",
        "No-RT and no-template controls.",
        "Normalise to the gene's total output, not to a housekeeping gene. The claim is a change in the RATIO of two isoforms; total-gene normalisation is what makes it a fraction rather than an expression change.",
    ],
    "targeted long-read cDNA": [
        "Size-select or verify the amplicon pool on a Bioanalyzer or TapeStation before sequencing; a dominant short product will consume the run.",
        "Include the -LPS and +LPS libraries with distinct barcodes in one run.",
        "Expect the full-length product; reads shorter than the expected amplicon are PCR or library artefacts, not short isoforms.",
        "No-template control carried through library prep.",
    ],
    "3' RACE": [
        "No-RT and no-template controls.",
        "Oligo-dT priming will also prime at internal A-rich stretches; confirm the 3' end by sequencing, not by size.",
        "Both conditions in one batch.",
    ],
}
CONTROLS["unique-region qPCR / ddPCR (+ 5' RACE to fix the TSS)"] = CONTROLS["qPCR"]
CONTROLS["3'-region qPCR / ddPCR"] = CONTROLS["qPCR"]
CONTROLS["junction-spanning qPCR / ddPCR"] = CONTROLS["qPCR"]
CONTROLS["intron-spanning qPCR / ddPCR"] = CONTROLS["qPCR"]

ROLE_LABEL = {
    "qPCR_F": "qPCR forward", "qPCR_R": "qPCR reverse",
    "longread_F": "long-read outer forward", "longread_R": "long-read outer reverse",
    "RACE5_GSP2_inner": "5' RACE inner GSP (nested PCR, antisense)",
    "RACE5_GSP1_outer": "5' RACE outer GSP (first PCR, antisense)",
    "RACE3_GSP2_inner": "3' RACE inner GSP (nested PCR, sense)",
    "RACE3_GSP1_outer": "3' RACE outer GSP (first PCR, sense)",
}

out = []
w = out.append

w("# Per-candidate experimental plans\n")
w("Generated by `scripts/32_assay_designs_doc.py` from the tables in `results/tables/`. "
  "Every sequence, size and count below is read from those files; none is typed by hand.\n")
w("## How to read an entry\n")
w("**Switch** names the two transcripts whose ratio changes. The candidate is the isoform "
  "whose fraction moves with LPS; the partner is the most-opposed isoform at the same locus. "
  "A positive dIF means the candidate's share of the locus RISES on LPS.\n")
w("**Platform** is the question this project exists to keep straight: whether a short-read "
  "Illumina experiment against the standard annotation could have found this switch, or "
  "whether it is visible only because of the PacBio assembly. Two situations require long "
  "reads: either side having a non-matching class code, and -- less obvious -- both isoforms "
  "mapping to the SAME reference transcript, which makes the switch invisible to any "
  "isoform-level short-read analysis no matter how deeply sequenced.\n")
w("**Expected readout** gives the predicted product size in BOTH isoforms. Where the partner "
  "column says *no product*, the assay is isoform-specific by construction; where both sizes "
  "are given, one reaction reports the ratio and the two bands are the readout.\n")
w("**Off-target loci** is measured, not predicted: every oligo was searched against all "
  "296,613 transcripts of the reference by its 3'-terminal 15 nt, then extended to its full "
  "length. Binding several isoforms of the same gene is expected and often intended. Binding "
  "a *different* gene is a defect, and is stated per oligo.\n")

w("## Before you order: three caveats that apply to the whole list\n")
nunspl = sum(1 for v in seqver.values() if B(v["pipeline_fasta_was_unspliced"]))
w(f"1. **The reference FASTA is not uniformly spliced cDNA.** 36,115 of its 296,613 records "
  f"(12.2%) are unspliced genomic intervals. {nunspl} of the 97 sequences needed here were "
  f"among them and were rebuilt from hg38 using the GFF3 exon coordinates, a method validated "
  f"by reproducing four already-correct transcripts base-for-base on both strands. Primers "
  f"below are designed on verified spliced sequence. Anything else in the project that read "
  f"sequence or ORFs from that FASTA should be re-checked.\n")
w("2. **These oligos are designed and screened, not tested.** The specificity numbers are exact-"
  "match counts against a transcriptome, which is a far better check than a thermodynamic score "
  "but is not a gel. Every pair still needs its standard curve and melt curve.\n")
w("3. **Antibody and mass-spectrometry routes are specified, not validated.** Where an entry "
  "calls for an isoform-resolving western, the epitope requirement is stated so a human can "
  "check whether such an antibody exists. I cannot validate antibodies.\n")

# ---------------------------------------------------------------- summary table
w("## Summary\n")
by_assay = Counter(a["primary_assay"] for a in assign)
w("| primary assay | candidates |")
w("|---|---|")
for k, v in by_assay.most_common():
    w(f"| {k} | {v} |")
w("")

ill = Counter()
for a in assign:
    d = detect.get(a["isoform_id"])
    ill[d["platform_required"] if d else "not classified"] += 1
w("| platform requirement | candidates |")
w("|---|---|")
for k, v in ill.most_common():
    w(f"| {k} | {v} |")
w("")

# ---------------------------------------------------------------- entries
assign_sorted = sorted(assign, key=lambda a: -abs(F(a["own_dIF"])))
w("## Candidates\n")
w("Ordered by effect size (|dIF|) in the dataset that discovered them.\n")

for a in assign_sorted:
    iso, gene = a["isoform_id"], a["gene_name"]
    reg = regions.get(iso, {})
    det = detect.get(iso, {})
    dif = F(a["own_dIF"])
    direction = "RISES" if dif > 0 else "FALLS"
    src = a["discovered_in"]
    floor = POWER.get(src, 0.16)

    w(f"### {gene} — {a['primary_event']}\n")
    w(f"**Switch.** `{iso}` (candidate) against `{a['partner']}` (partner) at locus "
      f"`{a['gene_id']}`. Discovered in **{src}**, evidence tier {a['tier']}, "
      f"set *{a['set']}*. dIF = **{dif:+.3f}** — the candidate isoform **{direction}** "
      f"as a share of the locus on LPS"
      + (f"; in the other system dIF = {F(a['other_dIF']):+.3f}." if a["other_dIF"] else ".") + "\n")

    if det:
        prov = []
        if B(det.get("assembly_contributed_candidate")):
            prov.append("the candidate model was emitted by the PacBio assembly")
        if B(det.get("assembly_contributed_partner")):
            prov.append("the partner model was emitted by the PacBio assembly")
        w(f"**Platform. {det['platform_required']}** — {det['reason']}. "
          f"Class codes: candidate `{det['class_code_candidate']}`, partner "
          f"`{det['class_code_partner']}`."
          + (" " + "; ".join(prov).capitalize() +
             " — note this is provenance, not novelty: which assembler emitted a model is a "
             "different question from whether its structure is new." if prov else "") + "\n")

    nested = " The candidate is wholly contained within its partner, so no amplicon can be " \
             "specific to it by position alone — this is why the assay below is not a qPCR." \
             if B(a["is_nested"]) else ""
    w(f"**Structure.** {a['primary_event']}; TSS {a['tss_distance_bp']} bp apart, "
      f"3' ends {a['tts_distance_bp']} bp apart. Candidate {reg.get('candidate_len','?')} nt, "
      f"partner {reg.get('partner_len','?')} nt, sharing {reg.get('shared_bp','?')} nt "
      f"({reg.get('shared_frac_of_candidate','?')} of the candidate); longest candidate-only "
      f"run {a['longest_unique_bp']} nt.{nested}\n")
    if B(reg.get("low_overlap_flag")):
        w("> **Flag.** These two transcripts share under 200 nt of exonic sequence. That makes "
          "them easy to tell apart but hard to regard as two isoforms of one gene; confirm the "
          "locus is not a merge of two neighbouring genes before investing in this one.\n")
    if B(reg.get("short_model_flag")):
        w("> **Flag.** The candidate model is under 300 nt. Treat it as a possible assembly "
          "fragment rather than a complete transcript until the long-read amplicon confirms it.\n")

    ptc = " The candidate carries a premature termination codon, so the NMD route below is " \
          "the point of the experiment." if B(a["PTC_candidate"]) else ""
    w(f"**Consequence.** ORF {a['orf_len_candidate']} nt (candidate) against "
      f"{a['orf_len_partner']} nt (partner), difference {a['orf_len_delta']} nt; "
      + ("same ORF length, so the consequence is more likely translational than compositional — "
         "note that equal length does not mean equal sequence" if B(a["same_orf_length"])
         else "protein-changing") + f".{ptc}\n")

    w(f"**Assay.** {a['primary_assay']}. Fallback: {a['fallback_assay']}. "
      f"Orthogonal: {a['orthogonal_assays']}\n")

    ol = sorted(oligos.get(iso, []), key=lambda o: o["oligo_role"])
    if ol:
        w("| oligo | sequence (5'->3') | len | Tm | GC% | off-target loci |")
        w("|---|---|---|---|---|---|")
        for o in ol:
            off = o["offtarget_loci"]
            flag = "0" if str(off) == "0" else f"**{off}**"
            w(f"| {ROLE_LABEL.get(o['oligo_role'], o['oligo_role'])} | `{o['sequence']}` | "
              f"{o['length']} | {o['tm_C']} | {o['gc_pct']} | {flag} |")
        w("")
        pr = [p for p in prep.get(iso, [])]
        for o in ol:
            if str(o["offtarget_loci"]) not in ("0", ""):
                w(f"> `{ROLE_LABEL.get(o['oligo_role'], o['oligo_role'])}` binds "
                  f"{o['offtarget_loci']} other loci ({o['offtarget_locus_names']}). "
                  f"{'This was the best of the alternatives tested; redesign by hand or mask repeats before ordering.' if o['selection'].startswith('BEST') else ''}\n")
        # Each readout is tied to the oligos that produce it, and the design-level
        # prediction is checked against the empirical scan rather than reported alone.
        emp = {p["pair"]: p for p in prep.get(iso, [])}
        GROUPS = [("qPCR_F/qPCR_R", ("qPCR_F", "qPCR_R"), "qPCR / ddPCR pair"),
                  ("longread_F/longread_R", ("longread_F", "longread_R"),
                   "targeted long-read outer pair"),
                  (None, ("RACE5_GSP1_outer",), "5' RACE, outer GSP"),
                  (None, ("RACE5_GSP2_inner",), "5' RACE, inner (nested) GSP"),
                  (None, ("RACE3_GSP1_outer",), "3' RACE, outer GSP"),
                  (None, ("RACE3_GSP2_inner",), "3' RACE, inner (nested) GSP")]
        byrole = {o["oligo_role"]: o for o in ol}
        for pairkey, roles, label in GROUPS:
            if roles[0] not in byrole:
                continue
            o = byrole[roles[0]]
            c, p = o["expected_product_candidate_bp"], o["expected_product_partner_bp"]
            if not c:
                continue
            if p in ("no product", "no site in partner"):
                line = (f"**Expected readout — {label}.** {c} bp from the candidate; "
                        f"nothing from the partner, so this reaction reports the candidate alone.")
            elif str(c) == str(p):
                line = (f"**Expected readout — {label}.** {c} bp from BOTH isoforms. This pair "
                        f"cannot discriminate by size; the product must be sequenced.")
            else:
                line = (f"**Expected readout — {label}.** {c} bp from the candidate, {p} bp "
                        f"from the partner — one reaction, two bands, and their ratio is the "
                        f"measurement.")
            e = emp.get(pairkey) if pairkey else None
            if e is not None:
                amp = B(e["amplifies_partner"])
                predicted_specific = p in ("no product", "no site in partner")
                if predicted_specific and amp:
                    line += (" **The transcriptome scan contradicts this prediction: the pair "
                             "does amplify the partner.** Treat it as non-discriminating and "
                             "redesign, or read it by sequencing rather than by Ct.")
                elif predicted_specific and not amp:
                    line += " The transcriptome scan confirms no partner product."
                elif not predicted_specific and amp:
                    line += " The scan confirms both isoforms amplify, as intended here."
            w(line + "\n")

    w(f"**Supports the switch if.** The candidate's share of the locus is higher in +LPS than "
      f"in -LPS by at least {floor:.2f} in the same direction as the sequencing "
      f"(dIF {dif:+.3f}), across three independent biological replicates.\n")
    w(f"**Falsified if.** The shift is in the opposite direction, or its magnitude is below "
      f"{floor:.2f} — the minimum detectable |dIF| at n=3 and 80% power in {src}. "
      f"A null result below that threshold is uninformative rather than negative: it means "
      f"the experiment was underpowered, and the honest conclusion is to add replicates.\n")

    ctl = CONTROLS.get(a["primary_assay"])
    if ctl:
        w("**Controls.**\n")
        for c in ctl:
            w(f"- {c}")
        w("")

os.makedirs("docs", exist_ok=True)
open("docs/ASSAY_DESIGNS.md", "w").write("\n".join(out) + "\n")
print(f"docs/ASSAY_DESIGNS.md written: {len(out)} lines, {len(assign_sorted)} candidates")
print(f"oligos referenced: {sum(len(v) for v in oligos.values())}")
